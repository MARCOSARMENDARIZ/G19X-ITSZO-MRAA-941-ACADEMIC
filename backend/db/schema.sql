-- Esquema inicial de Plataforma Bienestar IA
-- PostgreSQL. Ejecutar en una base de datos nueva y vacía.
-- Este archivo crea estructura; no contiene usuarios ni credenciales.

BEGIN;

CREATE TABLE usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,
    rol VARCHAR(30) NOT NULL DEFAULT 'usuario',
    CONSTRAINT usuarios_email_unique UNIQUE (email)
);

CREATE TABLE perfiles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL UNIQUE,
    telefono VARCHAR(30),
    puesto VARCHAR(150),
    departamento VARCHAR(150),
    fecha_ingreso DATE DEFAULT CURRENT_DATE,
    foto_url VARCHAR(500),
    CONSTRAINT perfiles_usuario_fk
        FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);

CREATE TABLE encuestas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descripcion TEXT NOT NULL DEFAULT '',
    estado VARCHAR(30) NOT NULL DEFAULT 'activa',
    creado_por INTEGER,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_cierre TIMESTAMPTZ,
    CONSTRAINT encuestas_creado_por_fk
        FOREIGN KEY (creado_por) REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE preguntas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encuesta_id INTEGER NOT NULL,
    texto_pregunta TEXT NOT NULL,
    tipo_respuesta VARCHAR(20) NOT NULL,
    orden INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT preguntas_tipo_check
        CHECK (tipo_respuesta IN ('opcion', 'escala', 'texto')),
    CONSTRAINT preguntas_encuesta_fk
        FOREIGN KEY (encuesta_id) REFERENCES encuestas(id) ON DELETE CASCADE
);

CREATE TABLE opciones_pregunta (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_id INTEGER NOT NULL,
    texto_opcion TEXT NOT NULL,
    CONSTRAINT opciones_pregunta_fk
        FOREIGN KEY (pregunta_id) REFERENCES preguntas(id) ON DELETE CASCADE
);

CREATE TABLE respuestas_encuesta (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encuesta_id INTEGER NOT NULL,
    usuario_id INTEGER,
    fecha_respuesta TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT respuestas_encuesta_encuesta_fk
        FOREIGN KEY (encuesta_id) REFERENCES encuestas(id) ON DELETE CASCADE,
    CONSTRAINT respuestas_encuesta_usuario_fk
        FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL,
    CONSTRAINT respuestas_encuesta_usuario_unico UNIQUE (encuesta_id, usuario_id)
);

CREATE TABLE detalle_respuestas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    respuesta_encuesta_id INTEGER NOT NULL,
    pregunta_id INTEGER NOT NULL,
    opcion_id INTEGER,
    valor_numero NUMERIC(10, 2),
    valor_texto TEXT,
    CONSTRAINT detalle_respuestas_cabecera_fk
        FOREIGN KEY (respuesta_encuesta_id) REFERENCES respuestas_encuesta(id) ON DELETE CASCADE,
    CONSTRAINT detalle_respuestas_pregunta_fk
        FOREIGN KEY (pregunta_id) REFERENCES preguntas(id) ON DELETE CASCADE,
    CONSTRAINT detalle_respuestas_opcion_fk
        FOREIGN KEY (opcion_id) REFERENCES opciones_pregunta(id) ON DELETE SET NULL,
    CONSTRAINT detalle_respuestas_pregunta_unica UNIQUE (respuesta_encuesta_id, pregunta_id)
);

CREATE TABLE propuestas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER,
    titulo VARCHAR(255) NOT NULL,
    descripcion TEXT NOT NULL,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT propuestas_usuario_fk
        FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE recuperacion_password (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    codigo_hash CHAR(64) NOT NULL,
    expira_en TIMESTAMPTZ NOT NULL,
    intentos INTEGER NOT NULL DEFAULT 0,
    verificado_en TIMESTAMPTZ,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT recuperacion_password_intentos_check CHECK (intentos >= 0),
    CONSTRAINT recuperacion_password_usuario_fk
        FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);



COMMIT;